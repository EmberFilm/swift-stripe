#!/usr/bin/env python3
"""
Generate Swift request types for every Stripe API operation from Stripe's OpenAPI spec.

    Scripts/generate-requests.py spec3.sdk.json [--out Sources/Stripe/Requests/Generated] [--check]

Operations are attributed to resources through the spec's `x-stripeOperations`; a resource's
operations are emitted as nested namespaces of its Swift type, so the request for creating a
customer is `Stripe.Customers.Customer.Create.Request`, and a list operation's page is
`Stripe.Customers.Customer.List.Response` (a `Stripe.Page<Customer>`). Path parameters are not
part of the request type — they are the client method's arguments.

Type rules:
  string / integer / boolean          -> String / Int / Bool
  number                              -> Decimal
  integer with format unix-time       -> Date
  string with enum                    -> nested String enum named after the property
  object with properties              -> nested struct named after the property
  object with only additionalProperties -> [String: T]
  object with nothing                 -> empty marker struct
  array                               -> [T]
  anyOf [T, ""]                       -> T   (the empty-string "unset" idiom is dropped)
  anyOf [integer, {gt,gte,lt,lte}]    -> Stripe.RangeQuery
  anyOf [object, string]              -> String (an ID; the inline form is not modelled)
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import pathlib
import re
import sys

_models_spec = importlib.util.spec_from_file_location(
    "generate_models", pathlib.Path(__file__).with_name("generate-models.py"))
gm = importlib.util.module_from_spec(_models_spec)
_models_spec.loader.exec_module(gm)
camel, pascal, ident, enum_case, doc, Enum = gm.camel, gm.pascal, gm.ident, gm.enum_case, gm.doc, gm.Enum

HEADER = """//
//  {file}
//  Stripe
//
//  Generated by Scripts/generate-requests.py from Stripe's OpenAPI spec ({version}).
//  Do not edit by hand.
//

#if canImport(FoundationEssentials)
import FoundationEssentials
#else
import Foundation
#endif
"""

RANGE_QUERY = "Stripe.RangeQuery"


def plural(noun: str) -> str:
    if noun.endswith("y") and noun[-2:-1] not in "aeiou":
        return noun[:-1] + "ies"
    if noun.endswith(("s", "x", "ch", "sh")):
        return noun + "es"
    return noun + "s"


def swift_type_for_resource(name: str) -> str | None:
    """The Swift type a resource schema is modelled as, or None when it has no model."""
    if name in gm.RESOURCES:
        path = gm.RESOURCES[name]
        return path.lstrip("/") if path.startswith("/") else f"Stripe.{path}"
    if name in gm.RESOURCE_TYPES:
        t = gm.RESOURCE_TYPES[name]
        return t.replace("Generated.", "Stripe.") if t.startswith("Generated.") else t
    return None


class Field:
    def __init__(self, name: str, swift_type: str, required: bool, description: str | None):
        self.name, self.swift_type, self.required, self.description = name, swift_type, required, description


class Struct:
    def __init__(self, name: str, description: str | None):
        self.name, self.description = name, description
        self.fields: list[Field] = []
        self.enums: list[Enum] = []
        self.nested: list[Struct] = []

    def render(self, indent: str) -> str:
        i = indent
        out = ""
        if self.description:
            out += f"{i}/// {self.description}\n"
        out += f"{i}public struct {ident(self.name)}: Codable, Hashable, Sendable {{\n"
        if not self.fields:
            out += f"{i}    public init() {{}}\n{i}}}\n"
            return out
        for f in self.fields:
            if f.description:
                out += f"{i}    /// {f.description}\n"
            opt = "" if f.required else "?"
            out += f"{i}    public var {ident(f.name)}: {f.swift_type}{opt}\n"
        out += f"\n{i}    private enum CodingKeys: String, CodingKey {{\n"
        for f in self.fields:
            out += f"{i}        case {ident(f.name)}\n"
        out += f"{i}    }}\n\n"
        params = [f"{ident(f.name)}: {f.swift_type}" + ("" if f.required else "? = nil") for f in self.fields]
        out += f"{i}    public init(\n" + ",\n".join(f"{i}        {p}" for p in params) + f"\n{i}    ) {{\n"
        for f in self.fields:
            out += f"{i}        self.{ident(f.name)} = {ident(f.name)}\n"
        out += f"{i}    }}\n"
        for e in self.enums:
            out += "\n" + e.render(i + "    ")
        for n in self.nested:
            out += "\n" + n.render(i + "    ")
        out += f"{i}}}\n"
        return out


class UnionEnum:
    """A parameter that is either a scalar or one of a few keywords (`integer | "now"`)."""

    def __init__(self, name: str, value_type: str, keywords: list[str], description: str | None):
        self.name, self.value_type, self.keywords, self.description = name, value_type, keywords, description

    def render(self, indent: str) -> str:
        i = indent
        out = ""
        if self.description:
            out += f"{i}/// {self.description}\n"
        out += f"{i}public enum {ident(self.name)}: Codable, Hashable, Sendable {{\n"
        out += f"{i}    case value({self.value_type})\n"
        for k in self.keywords:
            out += f"{i}    case {enum_case(k)}\n"
        out += f"\n{i}    public init(from decoder: any Decoder) throws {{\n"
        out += f"{i}        let container = try decoder.singleValueContainer()\n"
        out += f"{i}        if let value = try? container.decode({self.value_type}.self) {{ self = .value(value); return }}\n"
        out += f"{i}        switch try container.decode(String.self) {{\n"
        for k in self.keywords:
            out += f'{i}        case "{k}": self = .{enum_case(k)}\n'
        out += f"{i}        case let other: throw DecodingError.dataCorruptedError(in: container, debugDescription: \"unknown keyword \\(other)\")\n"
        out += f"{i}        }}\n{i}    }}\n\n"
        out += f"{i}    public func encode(to encoder: any Encoder) throws {{\n"
        out += f"{i}        var container = encoder.singleValueContainer()\n"
        out += f"{i}        switch self {{\n"
        out += f"{i}        case .value(let value): try container.encode(value)\n"
        for k in self.keywords:
            out += f'{i}        case .{enum_case(k)}: try container.encode("{k}")\n'
        out += f"{i}        }}\n{i}    }}\n{i}}}\n"
        return out


class Operation:
    def __init__(self, resource: str, method_name: str, http: str, path: str, op: dict):
        self.resource, self.method_name, self.http, self.path, self.op = resource, method_name, http, path, op
        self.name = pascal(method_name)
        self.request: Struct | None = None
        self.response: str | None = None
        self.notes: list[str] = []


class Generator:
    def __init__(self, spec: dict):
        self.spec = spec
        self.schemas = spec["components"]["schemas"]
        self.notes: list[str] = []

    # ---- attribution -------------------------------------------------------------------

    def operations(self) -> dict[str, list[Operation]]:
        """Operations grouped by the resource that owns them."""
        claimed: dict[tuple[str, str], Operation] = {}
        collection_only: list[tuple[str, dict]] = []
        for name, schema in self.schemas.items():
            for entry in schema.get("x-stripeOperations", []):
                key = (entry["operation"], entry["path"])
                if entry.get("method_on") == "collection":
                    collection_only.append((name, entry))
                    continue
                op = self.spec["paths"][entry["path"]][entry["operation"]]
                claimed[key] = Operation(name, entry["method_name"], entry["operation"], entry["path"], op)
        # The same operation on two paths: `/v1/tax_ids` and `/v1/customers/{customer}/tax_ids`
        # (the second is the customer's `create_tax_id`), or `/v1/account` and
        # `/v1/accounts/{account}` (the first is `retrieve_current`).
        by_name: dict[tuple[str, str], list[Operation]] = {}
        for op in claimed.values():
            by_name.setdefault((op.resource, op.method_name), []).append(op)
        for (resource, name), ops in by_name.items():
            if len(ops) < 2:
                continue
            remaining = []
            for op in ops:
                params = re.findall(r"\{(\w+)\}", op.path)
                if params and params[0] in self.schemas and params[0] != resource:
                    owner = params[0]
                    short = resource.split(".")[-1]
                    op.resource = owner
                    op.method_name = f"{name}_{plural(short) if name == 'list' else short}"
                    op.name = pascal(op.method_name)
                else:
                    remaining.append(op)
            if len(remaining) > 1:
                for op in remaining:
                    if "{" not in op.path:
                        op.method_name = f"{name}_current"
                        op.name = pascal(op.method_name)
        # A collection entry (`customer` listing `customer_balance_transaction`) is an operation on
        # the owner, named the way Stripe's SDKs name it: `customers.listBalanceTransactions`,
        # `customers.createTaxId`, `accounts.retrieveCapability`.
        for owner, entry in collection_only:
            key = (entry["operation"], entry["path"])
            if key in claimed:
                continue
            op = self.spec["paths"][entry["path"]][entry["operation"]]
            child = entry["method_name"]
            if child not in self.schemas:
                # `charge.refunds` names the operation, not the child: find the child by the response
                schema = next(iter(op["responses"]["200"]["content"].values()))["schema"]
                ref = schema.get("$ref") or schema.get("properties", {}).get("data", {}).get("items", {}).get("$ref")
                if not ref:
                    self.notes.append(f"{owner}: collection op on unknown resource {child} ({entry['path']})")
                    continue
                child = ref.split("/")[-1]
            short = child.split(".")[-1]
            owner_short = owner.split(".")[-1]
            if short.startswith(owner_short + "_"):
                short = short[len(owner_short) + 1:]
            verb = entry["method_type"]
            name = f"{verb}_{plural(short) if verb == 'list' else short}"
            if any(o.resource == owner and o.method_name == name for o in claimed.values()):
                self.notes.append(f"{owner}: {name} already defined; {entry['path']} skipped")
                continue
            claimed[key] = Operation(owner, name, entry["operation"], entry["path"], op)
        grouped: dict[str, list[Operation]] = {}
        for op in claimed.values():
            grouped.setdefault(op.resource, []).append(op)
        return grouped

    # ---- parameters --------------------------------------------------------------------

    def parameters(self, op: Operation) -> tuple[dict, list[str], list[str]]:
        """(properties, required, order) for an operation's non-path parameters."""
        props: dict = {}
        required: list[str] = []
        if op.http == "get":
            for prm in op.op.get("parameters", []):
                if prm.get("in") != "query":
                    continue
                schema = dict(prm["schema"])
                schema.setdefault("description", prm.get("description"))
                props[prm["name"]] = schema
                if prm.get("required"):
                    required.append(prm["name"])
        else:
            body = op.op.get("requestBody", {}).get("content", {}).get("application/x-www-form-urlencoded", {}).get("schema", {})
            props = body.get("properties", {})
            required = body.get("required", [])
        return props, required, list(props)

    # ---- types -------------------------------------------------------------------------

    def resolve(self, node: dict, prop: str, owner: Struct, path: str) -> str:
        """The Swift type for a parameter schema, adding nested declarations to `owner`."""
        if "anyOf" in node:
            alts = [a for a in node["anyOf"] if not (a.get("type") == "string" and a.get("enum") == [""])]
            if len(alts) == 1:
                return self.resolve(alts[0], prop, owner, path)
            types = sorted(a.get("type", "object") for a in alts)
            if types == ["integer", "object"] and set(alts[1 if alts[0].get("type") == "integer" else 0].get("properties", {})) <= {"gt", "gte", "lt", "lte"}:
                return RANGE_QUERY
            if "string" in types and "object" in types:
                self.notes.append(f"{path}: object-or-ID parameter modelled as the ID")
                return "String"
            keywords = [a for a in alts if a.get("type") == "string" and a.get("enum")]
            scalars = [a for a in alts if a.get("type") in ("integer", "boolean", "number")]
            if len(keywords) == 1 and len(scalars) == 1 and len(alts) == 2:
                # `expires_at: integer | "now"`, `up_to: integer | "inf"`: a value or a keyword
                name = pascal(prop)
                owner.nested.append(UnionEnum(name, self.resolve(scalars[0], prop, owner, path), keywords[0]["enum"], doc(node.get("description"))))
                return name
            if types.count("object") == len(types):
                self.notes.append(f"{path}: {len(types)} object alternatives; modelled as the first")
                return self.resolve(alts[0], prop, owner, path)
            self.notes.append(f"{path}: unmodelled anyOf {types}; modelled as the first")
            return self.resolve(alts[0], prop, owner, path)
        t = node.get("type")
        if t == "string":
            if node.get("format") == "currency":
                return "Stripe.Currency"
            if "enum" in node and len(node["enum"]) > 1 and not any("/" in v for v in node["enum"]):
                # an identifier list (`America/New_York`, …) is a String, not an enumeration
                name = pascal(prop)
                owner.enums.append(Enum(name, node["enum"], None))
                return name
            return "String"
        if t == "integer":
            return "Date" if node.get("format") == "unix-time" else "Int"
        if t == "number":
            return "Decimal"
        if t == "boolean":
            return "Bool"
        if t == "array":
            return f"[{self.resolve(node['items'], prop, owner, path + '[]')}]"
        if t == "object" or "properties" in node:
            if node.get("properties"):
                nested = self.build_struct(pascal(prop), node, path)
                owner.nested.append(nested)
                return nested.name
            extra = node.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return f"[String: {self.resolve(extra, prop, owner, path + '.*')}]"
            if extra is True or extra is None and not node.get("properties"):
                if extra is True:
                    return "[String: String]"
                nested = Struct(pascal(prop), doc(node.get("description")))
                owner.nested.append(nested)
                return nested.name
        self.notes.append(f"{path}: unmodelled schema {json.dumps(node)[:80]}; String")
        return "String"

    def build_struct(self, name: str, schema: dict, path: str) -> Struct:
        s = Struct(name, doc(schema.get("description")))
        required = set(schema.get("required", []))
        for prop, node in schema.get("properties", {}).items():
            swift_type = self.resolve(node, prop, s, f"{path}.{prop}")
            s.fields.append(Field(camel(prop), swift_type, prop in required, doc(node.get("description"))))
        return s

    # ---- responses ---------------------------------------------------------------------

    def response_type(self, op: Operation) -> str | None:
        content = op.op["responses"]["200"]["content"]
        schema = next(iter(content.values()))["schema"]
        if "$ref" in schema:
            return self.ref_type(schema["$ref"], op)
        if "anyOf" in schema:
            live = [a for a in schema["anyOf"] if "$ref" in a and not a["$ref"].split("/")[-1].startswith("deleted_")]
            return self.ref_type(live[0]["$ref"], op) if len(live) == 1 else None
        props = schema.get("properties", {})
        if "data" in props and "has_more" in props:
            items = props["data"]["items"]
            element = self.ref_type(items["$ref"], op) if "$ref" in items else None
            if element is None:
                op.notes.append("list of an unmodelled element; no Response")
                return None
            return f"Stripe.SearchPage<{element}>" if "next_page" in props else f"Stripe.Page<{element}>"
        return None

    def ref_type(self, ref: str, op: Operation) -> str | None:
        name = ref.split("/")[-1]
        if name.startswith("deleted_"):
            inner = swift_type_for_resource(name[len("deleted_"):])
            return f"DeletedObject<{inner}>" if inner else None
        t = swift_type_for_resource(name)
        if t is None:
            op.notes.append(f"response {name} has no Swift type")
        return t

    # ---- rendering ---------------------------------------------------------------------

    def render_resource(self, swift_type: str, ops: list[Operation]) -> str:
        out = f"extension {swift_type} {{\n"
        for op in sorted(ops, key=lambda o: o.name):
            out += f"    public enum {ident(op.name)} {{}}\n"
        out += "}\n"
        for op in sorted(ops, key=lambda o: o.name):
            if op.request is None and op.response is None:
                continue
            out += f"\n// {op.http.upper()} {op.path}\n"
            out += f"extension {swift_type}.{ident(op.name)} {{\n"
            if op.request is not None:
                out += op.request.render("    ")
            if op.response is not None:
                if op.request is not None:
                    out += "\n"
                out += f"    public typealias Response = {op.response}\n"
            out += "}\n"
        return out

    def run(self) -> dict[str, str]:
        files: dict[str, str] = {}
        version = self.spec["info"]["version"]
        for resource, ops in sorted(self.operations().items()):
            swift_type = swift_type_for_resource(resource)
            if swift_type is None:
                self.notes.append(f"{resource}: no Swift type; {len(ops)} operation(s) skipped")
                continue
            for op in ops:
                props, required, order = self.parameters(op)
                if props:
                    op.request = self.build_struct("Request", {"properties": props, "required": required}, f"{op.http} {op.path}")
                op.response = self.response_type(op)
                self.notes.extend(f"{op.http} {op.path}: {n}" for n in op.notes)
            path = swift_type[len("Stripe."):] if swift_type.startswith("Stripe.") else swift_type
            name = f"Generated.{path}.Requests.swift"
            files[name] = HEADER.format(file=name, version=version) + "\n" + self.render_resource(swift_type, ops)
        return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("spec")
    ap.add_argument("--out", default="Sources/Stripe/Requests/Generated")
    ap.add_argument("--check", action="store_true", help="exit 1 if the output differs from what is on disk")
    args = ap.parse_args()
    spec = json.load(open(args.spec))
    gen = Generator(spec)
    files = gen.run()
    out = pathlib.Path(args.out)
    if args.check:
        stale = [n for n, body in files.items() if not (out / n).exists() or (out / n).read_text() != body]
        extra = [p.name for p in out.glob("Generated.*.swift") if p.name not in files]
        for n in stale:
            print(f"out of date: {n}")
        for n in extra:
            print(f"unexpected: {n}")
        return 1 if stale or extra else 0
    out.mkdir(parents=True, exist_ok=True)
    for stale in out.glob("Generated.*.swift"):
        stale.unlink()
    for n, body in files.items():
        (out / n).write_text(body)
    for note in sorted(set(gen.notes)):
        print("note:", note, file=sys.stderr)
    print(f"wrote {len(files)} files to {out}/ ({spec['info']['version']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
