                        }
                    default: self = .unknown(type: type)
                    }
                }

                fileprivate func encode(into container: inout KeyedEncodingContainer<CodingKeys>) throws {
                    switch self {
                    case .blikAuthorize(let value): try container.encode(value, forKey: .blikAuthorize)
