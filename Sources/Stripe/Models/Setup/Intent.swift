                            self = .unknown(type: type)
                        }
                    case "use_stripe_sdk":
                        if let value = try container.decodeIfPresent([String: String].self, forKey: .useStripeSdk) {
                            self = .useStripeSdk(value)
                        } else {
                            self = .unknown(type: type)
